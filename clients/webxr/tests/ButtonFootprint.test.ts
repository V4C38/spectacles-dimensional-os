import { expect, it } from "vitest";
import * as THREE from "three";
import { ButtonFootprint } from "../src/presentation/ButtonFootprint";

it("spreads and softens a raised button's shadow down and sideways in physical units", () => {
  const footprint = new ButtonFootprint(0.4, 0.1, 0.05);
  const scale = new THREE.Vector3(0.5, 0.5, 0.5);
  footprint.setLift(0, scale);
  expect(footprint.visible).toBe(false);
  expect(footprint.material.uniforms.uStrength.value).toBe(0);
  const restSize = footprint.material.uniforms.uSize.value.clone() as THREE.Vector2;
  const restBlur = footprint.material.uniforms.uBlur.value;
  expect(footprint.position.x).toBe(0);
  expect(footprint.position.y).toBe(-0);
  footprint.position.z = -0.01;
  footprint.setLift(0.003, scale);
  expect(footprint.visible).toBe(true);
  const uniforms = footprint.material.uniforms;
  expect(uniforms.uStrength.value).toBeGreaterThan(0);
  expect(uniforms.uSize.value.x).toBeGreaterThan(restSize.x);
  expect(uniforms.uSize.value.y).toBeGreaterThan(restSize.y);
  expect(uniforms.uBlur.value).toBeGreaterThan(restBlur);
  expect(footprint.position.x).toBeGreaterThan(0);
  expect(footprint.position.y).toBeLessThan(-footprint.position.x);
  expect(footprint.position.z).toBe(-0.01);
  expect(uniforms.uPlaneSize.value.x - uniforms.uSize.value.x).toBeGreaterThan(uniforms.uBlur.value * 2);
  const physicalOffset = footprint.position.clone().multiply(scale);
  const spread = uniforms.uSize.value.x - restSize.x;
  const blur = uniforms.uBlur.value;
  scale.multiplyScalar(1.5);
  footprint.setLift(0.003, scale);
  expect(footprint.position.x * scale.x).toBeCloseTo(physicalOffset.x, 7);
  expect(footprint.position.y * scale.y).toBeCloseTo(physicalOffset.y, 7);
  expect(uniforms.uSize.value.x - 0.4 * scale.x).toBeCloseTo(spread, 7);
  expect(uniforms.uBlur.value).toBe(blur);
  footprint.setLift(0, scale);
  expect(uniforms.uBlur.value).toBe(restBlur);
  expect(footprint.visible).toBe(false);
  expect(uniforms.uStrength.value).toBe(0);
  expect(footprint.position.x).toBe(0);
  expect(footprint.material.depthWrite).toBe(false);
  footprint.dispose();
});
